import { writeFileSync } from 'fs';
import { createRequire } from 'module';

import {
  getExampleNumber,
  validatePhoneNumberLength,
} from 'libphonenumber-js/max';

import { prettify } from './utils.js';

const require = createRequire(import.meta.url);

const metadata = require('libphonenumber-js/metadata.max.json');
const examples = require('libphonenumber-js/examples.mobile.json');

const OUTPUT_PATH = './generated/phoneMasks.ts';

// E.164 allows at most 15 digits including the calling code.
const E164_MAX_DIGITS = 15;

const REQUIRED_DIGIT = '[0]';
const OPTIONAL_DIGIT = '[9]';

// Calling codes are prefix-free, so a typed code selects exactly one mask.
// The first country in the list is the main one for a shared calling code.
const getMainCountries = () =>
  Object.entries(metadata.country_calling_codes).map(
    ([dialCode, countries]) => ({
      dialCode,
      iso2: countries[0],
    }),
  );

// Possible national lengths are probed through the public API (not the compressed internal metadata).
const getNationalLengthRange = dialCode => {
  const maxNational = E164_MAX_DIGITS - dialCode.length;
  let min = null;
  let max = null;

  for (let length = 1; length <= maxNational; length++) {
    const result = validatePhoneNumberLength(
      `+${dialCode}${'9'.repeat(length)}`,
    );

    if (result === 'TOO_SHORT') continue;
    if (result === 'TOO_LONG') break;

    min ??= length;
    max = length;
  }

  return min === null ? null : { min, max };
};

const buildMask = ({ dialCode, iso2 }) => {
  const range = getNationalLengthRange(dialCode);
  const example = getExampleNumber(iso2, examples);

  if (!range) return null;

  // "+49 1512 3456789" -> "1512 3456789"
  const formattedNational = example
    ? example.formatInternational().slice(`+${dialCode} `.length)
    : '';

  let digitIndex = 0;
  let nationalMask = '';

  for (const char of formattedNational) {
    if (/\d/.test(char)) {
      nationalMask += digitIndex < range.min ? REQUIRED_DIGIT : OPTIONAL_DIGIT;
      digitIndex++;
    } else {
      nationalMask += char;
    }
  }

  // Example is shorter than the longest possible number: extend with optional digits.
  while (digitIndex < range.max) {
    nationalMask += OPTIONAL_DIGIT;
    digitIndex++;
  }

  return {
    dialCode,
    iso2,
    minLength: range.min,
    maxLength: range.max,
    mask: `+${dialCode}${nationalMask ? ' ' : ''}${nationalMask}`,
  };
};

const start = async () => {
  const masks = getMainCountries()
    .map(buildMask)
    .filter(Boolean)
    .reduce((acc, item) => ({ ...acc, [item.dialCode]: item }), {});

  const fallbackMask = `+${REQUIRED_DIGIT}${OPTIONAL_DIGIT.repeat(E164_MAX_DIGITS - 1)}`;

  const content = `/* eslint-disable */
// Generated by scripts/generate-phone-masks.js. Do not edit manually.

export type PhoneMask = {
  dialCode: string;
  iso2: string;
  minLength: number;
  maxLength: number;
  mask: string;
};

export const PHONE_MASKS_BY_DIAL_CODE: Record<string, PhoneMask> = ${JSON.stringify(masks)};

export const PHONE_FALLBACK_MASK = '${fallbackMask}';
`;

  writeFileSync(OUTPUT_PATH, await prettify(content));

  console.log(`Generated ${Object.keys(masks).length} masks -> ${OUTPUT_PATH}`);
};

start();
